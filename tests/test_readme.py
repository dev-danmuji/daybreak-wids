"""Example output in README.md must be real output.

Every ```text block preceded by ``<!-- output-of: daybreak-wids ... -->`` is
re-generated by running that command (synthetic fixtures, --dry-run); each
non-elided line of the block has to appear, in order, in the actual output.
Timestamps are normalised because they are printed in local time.
"""

import re
import shlex
import shutil
import textwrap
from pathlib import Path

import pytest
from click.testing import CliRunner

import daybreak.cli as cli

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
BLOCK = re.compile(r"<!-- output-of: (?P<cmd>.+?) -->\s*```text\n(?P<body>.*?)```", re.S)
TIME = re.compile(r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}")


def readme_blocks() -> list[tuple[str, str]]:
    # Blocks inside list items are indented; compare their text without the indentation.
    return [(m["cmd"].strip(), textwrap.dedent(m["body"]))
            for m in BLOCK.finditer(README.read_text(encoding="utf-8"))]


def test_readme_has_verified_examples():
    assert len(readme_blocks()) >= 2, "README.md lost its verified example output"


@pytest.mark.parametrize("cmd,body", readme_blocks(), ids=lambda v: Path(shlex.split(v)[-1]).stem if v.startswith("daybreak") else "")
def test_readme_example_output_is_real(cmd, body, tmp_path, monkeypatch):
    argv = shlex.split(cmd)
    assert argv[0] == "daybreak-wids"
    assert "--dry-run" in argv, "README examples must be safe to copy: use --dry-run"
    args = argv[1:]
    # Run against a private copy of the config so that a local networks.yaml next to
    # the repository's config.example.yaml cannot change the result.
    if "-c" in args:
        i = args.index("-c") + 1
        private = tmp_path / Path(args[i]).name
        shutil.copy(ROOT / args[i], private)
        args[i] = str(private)
    monkeypatch.chdir(ROOT)
    result = CliRunner().invoke(cli.main, args, catch_exceptions=False)
    assert result.exit_code == 0, result.output

    shown = body.splitlines()
    commands = [line[2:] for line in shown if line.startswith("$ ")]
    assert commands in ([], [cmd]), "the $ line of the block must match its output-of marker"
    expected = [TIME.sub("<time>", line) for line in shown
                if line.strip() not in ("", "...") and not line.startswith("$ ")]
    actual = [TIME.sub("<time>", line) for line in result.output.splitlines()]
    pos = 0
    for line in expected:
        try:
            pos = actual.index(line, pos) + 1
        except ValueError:
            pytest.fail(f"README line not found (in order) in the real output: {line!r}\n"
                        f"--- real output ---\n{result.output}")
